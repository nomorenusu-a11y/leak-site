export function buildNovemberPlan(options: {
  startDate: string;
  endDate: string;
  now: Date;
  existing?: { slug: string; title: string; published_at: string }[];
}): NovemberDraft[] {
  const { startDate, endDate, now, existing = [] } = options;
  if (!/^2026-11-\d{2}$/.test(startDate) || endDate !== "2026-11-30")
    throw new Error("November 2026 only");
  const drafts: NovemberDraft[] = [];
  const start = new Date(`${startDate}T00:00:00+09:00`);
  const end = new Date(`${endDate}T00:00:00+09:00`);
  let index = 0;
  for (
    let day = new Date(start), dayIndex = 0;
    day <= end;
    day = new Date(+day + 86400000), dayIndex++
  ) {
    const date = new Date(+day + 9 * 3600000).toISOString().slice(0, 10);
    const count = [10, 12, 11, 10, 11, 12, 10][dayIndex % 7];
    const occupied = existing.filter(
      (p) =>
        p.published_at &&
        new Date(new Date(p.published_at).getTime() + 9 * 3600000).toISOString().slice(0, 10) ===
          date,
    );
    const needed = Math.max(0, count - occupied.length);
    const last = +day + 23 * 3600000 + 10 * 60000;
    const first = Math.max(+day + 7 * 3600000 + 35 * 60000, +now + 90 * 60000);
    if (needed && first >= last)
      throw new Error(`No future publishing window for ${date}; start from tomorrow`);
    for (let slot = 0; slot < needed; slot++, index++) {
      const topicIndex = index % NOVEMBER_TOPICS.length;
      const t = NOVEMBER_TOPICS[topicIndex];
      const lens = LENSES[Math.floor(index / NOVEMBER_TOPICS.length) % LENSES.length];
      if (index >= NOVEMBER_TOPICS.length * LENSES.length)
        throw new Error("Editorial inventory exhausted");
      const [district, dong] =
        NOVEMBER_LOCATIONS[
          (index * 7 + Math.floor(index / NOVEMBER_TOPICS.length) * 3) % NOVEMBER_LOCATIONS.length
        ];
      const title = `${dong} ${t.name} | ${lens.question}`;
      const slug = `${date.replaceAll("-", "")}-november-${t.key}-${lens.key}`;
      const duration = last - first;
      const center = needed === 1 ? first : first + (duration * slot) / (needed - 1);
      const jitter =
        slot === 0 || slot === needed - 1 ? 0 : (((dayIndex * 17 + slot * 23) % 19) - 9) * 60000;
      const published_at = new Date(Math.floor((center + jitter) / 60000) * 60000).toISOString();
      const excerpt = `${district} ${dong}의 ${t.name} 관련 점검 안내입니다. ${lens.question}${lens.question.endsWith("?") ? "" : "."} 관찰 자료와 현장 검사, 상담 전 준비사항을 구분해 설명합니다.`;
      const matching = existing.filter(
        (p) => new Date(p.published_at) <= now && t.tags.some((tag) => p.title.includes(tag)),
      );
      const related = matching
        .slice(-3)
        .map(
          (p, i) =>
            `- [${t.tags.find((tag) => p.title.includes(tag))} 관련 공개 점검 글 ${i + 1}](/posts/${encodeURIComponent(p.slug)})`,
        )
        .join("\n");
      const content = `<!-- content-type:${lens.type} -->\n<!-- editorial-campaign:november-2026-v1 -->\n\n> 이 글은 ${district} ${dong} 출장 상담을 위한 점검 안내입니다. 해당 지역에서 실제로 진행한 시공 기록이나 측정 결과를 뜻하지 않습니다.\n\n${focusContent(t, lens)}\n\n## ${dong}에서 상담을 요청할 때\n\n지역과 건물 형태, 증상을 처음 본 시각을 알려주세요. **${t.name}**와 관련해 확인한 사실을 바탕으로 방문 점검 순서를 협의합니다. 사진만으로 원인이나 공사 범위를 확정하지 않습니다.\n\n노모어누수는 **서울·경기·인천 전 지역 출장 상담**이 가능합니다. 전화 [010-5700-4026](tel:01057004026) 또는 [사진과 증상으로 상담 신청](/#quote-form)을 이용해 주세요.\n\n## 관련 점검 안내\n\n${related || "- [공개된 누수 점검 글 보기](/posts)"}\n- [누수 상담 전 자주 묻는 질문](/faq)\n- [${dong} 관련 글 찾기](/posts?query=${encodeURIComponent(dong + " 누수")})`;
      drafts.push({
        title,
        slug,
        excerpt,
        content: content.replace(`**${t.name}**와 관련해`, `**${t.name}** 관련해서`),
        published_at,
        region_tags: [district],
        category: "leak",
        topicKey: t.key,
        tags: t.tags,
        type: lens.type,
        date,
      });
    }
  }
  return drafts;
}

export function validateNovemberPlan(drafts: NovemberDraft[], now: Date) {
  const errors: string[] = [];
  for (const field of ["title", "slug", "published_at"] as const)
    if (new Set(drafts.map((x) => x[field])).size !== drafts.length)
      errors.push(`Duplicate ${field}`);
  const bodies = new Set(
    drafts.map((x) => x.content.replace(/<!--.*?-->/g, "").replace(/\s/g, "")),
  );
  if (bodies.size !== drafts.length) errors.push("Duplicate content");
  for (const d of drafts) {
    if (new Date(d.published_at) <= now) errors.push(`Past publication: ${d.slug}`);
    if (d.title.length > 75) errors.push(`Long title: ${d.slug}`);
    if (d.content.length < 900) errors.push(`Insufficient detail: ${d.slug}`);
    if (/유레카|최태환|leak-site\.vercel\.app|\[\[AUTO_IMAGE/.test(d.content + d.title))
      errors.push(`Invalid content: ${d.slug}`);
    if (
      /생김 때|움직임 때|반복됨 확인|방문했습니다|해결했습니다|고객님 댁/.test(d.content + d.title)
    )
      errors.push(`Unverified or malformed wording: ${d.slug}`);
    if (!d.content.includes("실제로 진행한 시공 기록이나 측정 결과를 뜻하지 않습니다"))
      errors.push(`Missing advice disclosure: ${d.slug}`);
    if ((d.content.match(/\]\(\//g) || []).length < 3)
      errors.push(`Missing internal links: ${d.slug}`);
  }
  return errors;
}
